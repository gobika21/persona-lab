# Printing (or "Save as PDF") should include the step logs, which are collapsed on screen.
PRINT_JS = "addEventListener('beforeprint',()=>document.querySelectorAll('details').forEach(d=>d.open=true));"

RECORD_FORMAT = "persona-lab-run"


def _page(title: str, body: str) -> str:
    when = datetime.now(timezone.utc).strftime("%d %b %Y, %H:%M UTC")
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(title)}</title><style>{CSS}</style><script>{PRINT_JS}</script></head>
<body><main>{body}
<footer>Generated by <strong>Persona Lab</strong> on {when}. Automated and AI-assisted testing finds many,
but not all, accessibility problems; confirm important findings with real users and manual testing.</footer>
</main></body></html>"""


def _img_uri(data: bytes, mime: str = "image/jpeg") -> str:
    return f"data:{mime};base64,{base64.b64encode(data).decode()}"


def _sev(s: str) -> str:
    return f'<span class="sev {e(s or "")}">{e(s or "")}</span>'


def _barrier_cards(j: Journey) -> str:
    items = [(b, "Reported by the persona") for b in j.barriers] + [(b, "Detected automatically") for b in j.auto_findings]
    order = {"blocker": 0, "serious": 1, "minor": 2}
    items.sort(key=lambda x: order.get(x[0].get("severity"), 3))
    if not items:
        return '<p class="ok">No barriers were found on this journey.</p>'
    return "".join(
        f'<div class="card"><h3>{_sev(b.get("severity"))}{e(b.get("title", ""))}</h3><div>{e(b.get("detail", ""))}</div>'
        + (f'<div class="fix">{e(b["fix"])}</div>' if b.get("fix") else "")
        + f'<div class="small">{e(src)}{" · WCAG " + e(b["wcag"]) if b.get("wcag") else ""}{" · step " + str(b["step"]) if b.get("step") else ""}</div></div>'
        for b, src in items
    )


def _steps(j: Journey) -> str:
    words = {"open": "Opened the page", "press_key": "Pressed", "type_text": "Typed", "type_into": "Typed into", "click": "Clicked",
             "activate": "Activated", "read_page": "Read the page", "list_elements": "Listed", "find_text": "Searched",
             "scroll": "Scrolled", "look": "Looked", "go_back": "Went back", "report_barrier": "Hit a barrier", "finish": "Finished"}
    out = []
    for st in j.steps:
        shot = j.shots.get(st["n"])
        out.append(
            f'<li><span class="num" aria-hidden="true">{st["n"]}</span><div>'
            + (f'<div class="thought">“{e(st["thought"])}”</div>' if st.get("thought") else "")
            + f'<div><strong>{e(words.get(st["tool"], st["tool"]))}</strong> — {e(st["result"])}</div>'
            + (f'<details><summary class="small">What the screen reader said</summary><pre>{e(st["heard"])}</pre></details>' if st.get("heard") else "")
            + (f'<img class="shot" src="{_img_uri(shot)}" alt="Screen at step {st["n"]}" loading="lazy">' if shot else "")
            + "</div></li>"
        )
    return f'<ol class="steps">{"".join(out)}</ol>'


def _journey_section(j: Journey, heading_level: int = 2) -> str:
    p = PERSONAS[j.persona]
    verdict = ('<span class="ok">✓ Completed the goal</span>' if j.success
               else f'<span class="bad">✗ {"Stopped" if j.status == "stopped" else "Could not complete the goal"}</span>')
    h = f"h{heading_level}"
    return (f'<section><{h}>{e(p["label"])}</{h}>'
            f'<p class="small">{e(p["who"])}</p>'
            f'<div class="card"><strong>{verdict}</strong><p>{e(j.summary or j.error or "")}</p>'
            f'<div class="small">{len(j.steps)} steps</div></div>'
            f'<h3>Barriers</h3>{_barrier_cards(j)}'
            f'<details><summary><strong>Step-by-step log</strong></summary>{_steps(j)}</details></section>')


def export_journey(j: Journey) -> str:
    p = PERSONAS[j.persona]
    body = (f'<header class="top"><div class="brand">Persona Lab · Persona journey</div>'
            f'<h1>Can a {e(p["label"].lower())} {e(j.goal[0].lower() + j.goal[1:] if j.goal else "")}?</h1>'
            f'<div class="meta">{e(j.url)}</div></header>'
            f'<div class="hero"><div class="big {"ok" if j.success else "bad"}">{"✓" if j.success else "✗"}</div>'
            f'<div><strong>{"Yes, they completed it." if j.success else "No, they got stuck."}</strong><br>{e(j.summary or "")}</div></div>'
            f'<h2>Barriers found</h2>{_barrier_cards(j)}<h2>Step by step</h2>{_steps(j)}')
    return _page(f"Persona journey: {p['label']}", body)


def export_group(group: dict, journeys: list[Journey]) -> str:
    rows = "".join(
        f'<tr><th scope="row">{e(PERSONAS[j.persona]["label"])}</th>'
        f'<td>{"<span class=ok>✓ Completed</span>" if j.success else "<span class=bad>✗ Stuck</span>"}</td>'
        f'<td>{len(j.steps)}</td><td>{len(j.barriers) + len(j.auto_findings)}</td><td>{e((j.summary or j.error or "")[:220])}</td></tr>'
        for j in journeys
    )
    done = sum(1 for j in journeys if j.success)
    body = (f'<header class="top"><div class="brand">Persona Lab · Inclusion Score</div>'
            f'<h1>{done} of {len(journeys)} people could “{e(group["goal"])}”</h1><div class="meta">{e(group["url"])}</div></header>'
            f'<div class="hero"><div class="big {"ok" if done == len(journeys) else "bad"}">{done}/{len(journeys)}</div>'
            f'<div>Four AI personas tried the same task, each with only the senses and controls that person has: '
            f'keyboard only, a blind screen-reader user, color-blind, and low vision at 200% zoom.</div></div>'
            f'<h2>Results</h2><table><thead><tr><th>Person</th><th>Result</th><th>Steps</th><th>Barriers</th><th>What happened</th></tr></thead>'
            f'<tbody>{rows}</tbody></table>'
            + "".join(_journey_section(j) for j in journeys))
    return _page(f"Inclusion Score: {done}/{len(journeys)}", body)


def export_record(group: dict, journeys: list[Journey]) -> dict:
    """A run as data (no screenshots). Stable shape: History in the browser stores it and can import it back."""
    return {
        "format": RECORD_FORMAT, "version": 1,
        "exported_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "run": group,
        "journeys": [j.public() for j in journeys],
    }
